"""Assemble submissions/hgb_v1/: submission.py (with causal_features.py embedded verbatim) + model.

Usage: python scripts/build_hgb_submission.py [model.joblib] [out_name]
  default model: ~/neuralbench/save/hgb/hgb_all.joblib, out: submissions/hgb_v1 (+ .zip)
"""
import ast
import shutil
import sys
import zipfile
from pathlib import Path

import joblib

ROOT = Path(__file__).resolve().parents[1]
src_model = Path(sys.argv[1]) if len(sys.argv) > 1 else Path.home() / "neuralbench/save/hgb/hgb_all.joblib"
name = sys.argv[2] if len(sys.argv) > 2 else "hgb_v1"
out = ROOT / "submissions" / name
out.mkdir(parents=True, exist_ok=True)

# causal_features.py without its module docstring and imports (re-imported in the header).
feat_src = (ROOT / "scripts" / "causal_features.py").read_text()
tree = ast.parse(feat_src)
body_start = next(n.lineno for n in tree.body
                  if not isinstance(n, (ast.Expr, ast.Import, ast.ImportFrom)))
feat_body = "\n".join(feat_src.splitlines()[body_start - 1:])

HEADER = '''"""Track 03 submission: HistGradientBoostingRegressor (absolute error, W-bMAE weights) on causal
EEG features. Generated by scripts/build_hgb_submission.py -- do not edit by hand.

Per window: log band powers / ratios / artifact indicators per channel; per recording (state reset
at each recording): causal EMAs (30 s, 2 min, 5 min), difference to the recording's first-2-min
mean, elapsed time (= windows seen x window length). Never uses future windows or the recording end.
"""
import joblib
import numpy as np
import torch
from benchmark_utils.base_solver import CompetSolver
from scipy.signal import welch

# ---- verbatim copy of scripts/causal_features.py ----
'''

WRAPPER = '''
# ---- end of causal_features.py ----


class HGBStreamModel:
    def __init__(self, model, sfreq):
        self.model = model
        self.sfreq = float(sfreq)
        self.stream = None
        self.reset_state()

    def reset_state(self):
        """Called by the evaluator on a fresh copy at the start of every recording."""
        if self.stream is not None:
            self.stream.reset()

    def predict(self, X):
        # X: (B, C, T) consecutive windows of the current recording, in time order.
        x = X.detach().float().cpu().numpy()
        if self.stream is None:
            self.stream = CausalFeatureStream(step_s=x.shape[-1] / self.sfreq)
        # float32 round trip = exactly the training-time path (features cached as float32).
        f = window_features(x, self.sfreq).astype(np.float32).astype(np.float64)
        rows = np.stack([self.stream.update(fi) for fi in f]).astype(np.float32)
        pred = self.model.predict(rows)
        pred = np.clip(np.nan_to_num(pred, nan=0.0), 0.0, 600.0)
        return torch.as_tensor(pred, dtype=torch.float32, device=X.device)


class Solver(CompetSolver):
    name = "HGBCausalFeatures"

    def load_model(self, meta):
        bundle = joblib.load(meta["submission_dir"] / "model.joblib")
        return HGBStreamModel(bundle["model"], meta["sfreq"])
'''

(out / "submission.py").write_text(HEADER + feat_body + "\n" + WRAPPER)
bundle = joblib.load(src_model)
joblib.dump({"model": bundle["model"], "feature_names": bundle["feature_names"]}, out / "model.joblib")
zpath = ROOT / "submissions" / f"{name}.zip"
with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
    for f in ("submission.py", "model.joblib"):
        z.write(out / f, arcname=f)
print("wrote", out, "and", zpath, f"({zpath.stat().st_size / 1e6:.2f} MB)")
