    def reset_state(self):
        """Called by the evaluator on a fresh copy at the start of every recording."""
        if self.stream is not None:
            self.stream.reset()
        self.prev_out = None
        self.last_win = None
        self.gru_h = None
        self.gru_sum = None
        self.gru_cnt = 0
        self.gru_t = 0
        if self.kind == "mix3":
            self.gemb_h = [None] * len(self.gembs)
            self.emb_sum = [None] * len(self.encs)
            self.tcns.reset()

    def _grid_q(self, P):
        """(B, n_classes) probabilities -> metric-weighted, normalised grid distribution."""
        q = P * self.gru_omega
        return to_grid(q / q.sum(axis=1, keepdims=True), self.gru_edges, self.grid)

    def _grid_decide(self, Ps, Ph, elapsed):
        """30 s onset-grid decision for one window. Ps: class probabilities (n_classes,) of the sequence
        components, Ph: (n_grid,) mean HGB grid probabilities (unweighted), elapsed: time since the
        recording start at the end of the window (multiple of 5 s)."""
        idx = self.atom[int(round(elapsed)) % 30]
        if GRID_PI_CUTS:
            D = elapsed + np.arange(N_FINE) + 0.5
            pi = np.asarray(GRID_PI_VALUES)[np.searchsorted(np.asarray(GRID_PI_CUTS, dtype=np.float64), D, side="left")]
        else:
            pi = GRID_PI
        q = np.zeros(N_SLOT)
        for P in Ps:
            s = grid_slots(to_grid(P[None], self.gru_edges, self.grid)[0] @ self.fine, idx, pi) * self.slot_ws
            q += s / s.sum()
        h = grid_slots(Ph @ self.fine, idx, pi) * self.slot_wh
        return slot_median(self.alpha * q / len(Ps) + (1.0 - self.alpha) * h / h.sum())

    def _mix3_probs(self, f32, x):
        """f32: (B, 62) window features, x: (B, C, T) raw windows, time order -> seed-mean class
        probabilities (B, n_classes) of GRU-uw (10 seeds), TCN (10 seeds) and GRU-emb (3 encoder/GRU pairs)."""
        with torch.no_grad():
            xr = torch.clamp(torch.tensor(x, dtype=torch.float32) / self.cnn_scale, -self.cnn_clip, self.cnn_clip)
            embs = [enc(xr)[1].numpy().astype(np.float32) for enc in self.encs]  # (B, EMB) per seed
        rows, erows = [], [[] for _ in self.encs]
        for i, fi in enumerate(f32):
            self.gru_t += 1
            if self.gru_cnt < self.base_n:
                self.gru_sum = fi.copy() if self.gru_sum is None else self.gru_sum + fi
                for s, E in enumerate(embs):
                    self.emb_sum[s] = E[i].copy() if self.emb_sum[s] is None else self.emb_sum[s] + E[i]
                self.gru_cnt += 1
            n = np.float32(self.gru_cnt)
            el = np.float32(np.log1p(min(self.gru_t * 5.0, self.el_clip)))
            row = np.concatenate([fi, fi - self.gru_sum / n, [el]]).astype(np.float32)
            rows.append(row)
            for s, E in enumerate(embs):
                erows[s].append(np.concatenate([row, E[i], E[i] - self.emb_sum[s] / n]).astype(np.float32))
        rows = np.stack(rows)
        ps_g, ps_t, ps_e = [], [], []
        with torch.no_grad():
            xg = torch.tensor((rows - self.gru_mu) / self.gru_sd)[None]
            if self.gru_h is None:
                self.gru_h = [None] * len(self.grus)
            for i, net in enumerate(self.grus):
                logits, self.gru_h[i] = net(xg, self.gru_h[i])
                ps_g.append(torch.softmax(logits[0], -1).numpy().astype(np.float64))
            xt = torch.tensor((rows - self.tcn_mu) / self.tcn_sd)
            logits = torch.stack([self.tcns.step(xt[j]) for j in range(len(xt))])  # (B, S, n_out)
            ps_t = list(torch.softmax(logits, -1).permute(1, 0, 2).numpy().astype(np.float64))
            for s, net in enumerate(self.gembs):
                xe = torch.tensor((np.stack(erows[s]) - self.gemb_mu) / self.gemb_sd)[None]
                logits, self.gemb_h[s] = net(xe, self.gemb_h[s])
                ps_e.append(torch.softmax(logits[0], -1).numpy().astype(np.float64))
        return np.mean(ps_g, axis=0), np.mean(ps_t, axis=0), np.mean(ps_e, axis=0)

    def _gru_probs(self, f32):
        """f32: (B, 62) window features (float32), time order -> (B, n_classes) mean GRU probabilities."""
        rows = []
        for fi in f32:
            self.gru_t += 1
            if self.gru_cnt < self.base_n:
                self.gru_sum = fi.copy() if self.gru_sum is None else self.gru_sum + fi
                self.gru_cnt += 1
            base = self.gru_sum / np.float32(self.gru_cnt)
            el = np.float32(np.log1p(min(self.gru_t * 5.0, self.el_clip)))
            rows.append(np.concatenate([fi, fi - base, [el]]).astype(np.float32))
        x = torch.tensor((np.stack(rows) - self.gru_mu) / self.gru_sd)[None]
        if self.gru_h is None:
            self.gru_h = [None] * len(self.grus)
        ps = []
        with torch.no_grad():
            for i, net in enumerate(self.grus):
                logits, self.gru_h[i] = net(x, self.gru_h[i])
                ps.append(torch.softmax(logits[0], -1).numpy().astype(np.float64))
        return np.mean(ps, axis=0)

    def _smooth(self, pred, dt):
        out = np.empty_like(pred)
        for i, p in enumerate(pred):
            if self.prev_out is None or SMOOTH_A == 0:
                s = p
            else:
                s = SMOOTH_A * max(self.prev_out - dt, 0.0) + (1.0 - SMOOTH_A) * p
            out[i] = self.prev_out = s
        return out

    def _clean(self, x):
        """Invalid input -> finite values before anything else sees the window (features, CNN encoder,
        recurrent states, baselines). Invalid = NaN / inf samples, or a flat channel (finite samples with
        std < FLAT_SD_UV, or more than FLAT_SAME_FRAC of consecutive samples unchanged; clean public data:
        min std 1.67 uV, >= 99.8 % of samples change). A flat channel, or one with more than half of its
        samples NaN / inf, is replaced by that channel's last clean window (zeros if there is none yet);
        otherwise NaN / inf samples take the last valid sample of the channel (carried over from the previous
        window). Valid input is returned unchanged. Chosen on corrupted public-test recordings
        (KARAR_KATMANI_RAPORU.md, B_ASAMASI_RAPORU.md)."""
        bad = ~np.isfinite(x)
        n = (~bad).sum(axis=-1)
        xz = np.where(bad, 0.0, x).astype(np.float64)
        mean = xz.sum(axis=-1) / np.maximum(n, 1)
        sd = np.sqrt(np.where(bad, 0.0, (xz - mean[..., None]) ** 2).sum(axis=-1) / np.maximum(n, 1))
        with np.errstate(invalid="ignore"):
            same = (np.diff(x, axis=-1) == 0).mean(axis=-1)
        flat = (FLAT_SD_UV > 0) & (n >= 2) & ((sd < FLAT_SD_UV) | (same > FLAT_SAME_FRAC))
        if not bad.any() and not flat.any():
            self.last_win = x[-1].copy()
            return x
        x = x.copy()
        for i in range(x.shape[0]):
            for c in range(x.shape[1]):
                m = bad[i, c]
                if not m.any() and not flat[i, c]:
                    continue
                prev = self.last_win[c] if self.last_win is not None and self.last_win.shape == x[i].shape else None
                if flat[i, c] or m.mean() > 0.5:
                    x[i, c] = prev if prev is not None else 0.0
                else:
                    idx = np.where(~m, np.arange(m.size), -1)
                    np.maximum.accumulate(idx, out=idx)
                    first = prev[-1] if prev is not None else 0.0
                    x[i, c] = np.where(idx >= 0, x[i, c][np.maximum(idx, 0)], first)
            self.last_win = x[i].copy()
        return x

    def predict(self, X):
        # X: (B, C, T) consecutive windows of the current recording, in time order.
        x = self._clean(X.detach().float().cpu().numpy())
        if self.stream is None:
            self.stream = CausalFeatureStream(x.shape[-1] / self.sfreq, self.groups,
                                              core_index(range(x.shape[1])))
        # float32 round trip = exactly the training-time path (features cached as float32).
        f = window_features(x, self.sfreq).astype(np.float32)
        if self.window_groups:
            ext = window_features_ext(x, self.sfreq, self.ch_names, self.window_groups).astype(np.float32)
            f = np.concatenate([f, ext], axis=1)
        f32 = f
        f = f.astype(np.float64)
        rows = np.stack([self.stream.update(fi) for fi in f]).astype(np.float32)
        if self.padded is not None:
            rows = apply_padded_edges(rows, *self.padded)
        elif self.bin_edges is not None:
            rows = apply_bin_edges(rows, self.bin_edges)
        if self.kind == "ens_grid":
            P = np.mean([to_grid(hgb_predict_proba(t, rows), e, self.grid)
                         for t, e in zip(self.member_trees, self.member_edges)], axis=0)
            pred = decide(P, None, self.grid_omega, self.grid)
        elif self.kind == "mix":
            Wh = np.mean([to_grid(hgb_predict_proba(t, rows), e, self.grid)
                          for t, e in zip(self.member_trees, self.member_edges)], axis=0) * self.grid_omega
            Wh /= Wh.sum(axis=1, keepdims=True)
            q = self._gru_probs(f32)
            if self.gru_omega is not None:
                q = q * self.gru_omega
            q = to_grid(q / q.sum(axis=1, keepdims=True), self.gru_edges, self.grid)
            W = self.alpha * q + (1.0 - self.alpha) * Wh
            pred = decide(W, None, np.ones(W.shape[1]), self.grid)
        elif self.kind == "mix3":
            Ph = np.mean([to_grid(hgb_predict_proba(t, rows), e, self.grid)
                          for t, e in zip(self.member_trees, self.member_edges)], axis=0)
            Ps = self._mix3_probs(f32, x)
            Wh = Ph * self.grid_omega
            Wh /= Wh.sum(axis=1, keepdims=True)
            W = self.alpha * (self._grid_q(Ps[0]) + self._grid_q(Ps[1]) + self._grid_q(Ps[2])) / 3.0 + (1.0 - self.alpha) * Wh
            pred = decide(W, None, np.ones(W.shape[1]), self.grid)
            if GRID_ON:
                step = self.stream.step_s
                for i in range(len(pred)):
                    el = (self.stream.n_seen - len(pred) + i + 1) * step
                    # the grid tables assume window ends on multiples of 5 s; otherwise keep the plain decision
                    if abs(el - 5.0 * round(el / 5.0)) < 1e-6 and np.isfinite(Ph[i]).all():
                        pred[i] = self._grid_decide([P[i] for P in Ps], Ph[i], el)
        elif self.trees is not None:
            if self.kind == "dist":
                pred = decide(hgb_predict_proba(self.trees, rows), self.reps, self.omega, self.class_edges)
            else:
                pred = hgb_predict(self.trees, rows)
        elif self.kind == "dist":
            pred = decide(self.model.predict_proba(rows), self.reps, self.omega, self.class_edges)
        else:
            pred = np.asarray(self.model.predict(rows), dtype=np.float64)
        if CALIB_X is not None:
            pred = np.interp(pred, CALIB_X, CALIB_Y)
        pred = self._smooth(np.asarray(pred, dtype=np.float64), self.stream.step_s)
        pred = np.clip(np.nan_to_num(pred, nan=0.0), 0.0, 600.0)
        return torch.as_tensor(pred, dtype=torch.float32, device=X.device)


