SMOOTH_A = 0.0  # s_t = a*max(s_(t-1) - dt, 0) + (1-a)*p_t ; 0 = no smoothing
# Monotone calibration raw pred -> corrected pred (np.interp, flat outside); None = off.
# Learned on the out-of-fold CV predictions only (scripts/calibrate_oof.py).
CALIB_X = [7.8156890869140625, 10.6713228225708, 14.565106391906738, 17.374614715576172, 19.70377540588379, 22.655010223388672, 25.1632080078125, 27.546733856201172, 30.151559829711914, 32.72426223754883, 35.56931686401367, 38.41642379760742, 44.29916000366211, 52.04482650756836, 61.13038635253906, 70.7318115234375, 80.57726287841797, 124.60706329345703, 204.95736694335938, 338.3168029785156]
CALIB_Y = [15.000000000000002, 15.000000000000002, 19.999999999999996, 19.999999999999996, 19.999999999999996, 19.999999999999996, 20.398437999999942, 25.0, 30.0, 30.0, 35.0, 35.0, 40.0, 50.0, 60.0, 70.0, 85.0, 150.0, 215.0, 295.0]


def apply_bin_edges(X, edges):
    """Integer bin codes per feature (the model was trained on these); edges are constants."""
    return np.stack([np.searchsorted(e, X[:, j], side="right") for j, e in enumerate(edges)],
                    axis=1).astype(np.float32)


def decide(P, reps, omega, edges):
    """Continuous weighted median of the class distribution, class weights P_c * omega_c."""
    W = P * omega
    cum = np.cumsum(W, axis=1) / W.sum(axis=1, keepdims=True)
    k = np.minimum((cum < 0.5).sum(axis=1), P.shape[1] - 1)
    rows = np.arange(len(P))
    before = np.where(k > 0, cum[rows, np.maximum(k - 1, 0)], 0.0)
    mass = cum[rows, k] - before
    frac = np.clip((0.5 - before) / np.maximum(mass, 1e-12), 0, 1)
    return edges[k] + frac * (edges[k + 1] - edges[k])


class HGBStreamModel:
    def __init__(self, model, sfreq, bin_edges=None, bundle=None):
        self.model = model  # sklearn object, or None when numpy tree arrays are shipped
        self.bin_edges = bin_edges
        bundle = bundle or {}
        self.trees = bundle.get("trees")
        self.padded = bundle.get("padded_edges")
        self.kind = bundle.get("kind", "reg")
        self.groups = tuple(bundle.get("groups", ()))
        if self.kind == "dist":
            self.reps = np.asarray(bundle["reps"], dtype=np.float64)
            self.omega = np.asarray(bundle["omega"], dtype=np.float64)
            self.class_edges = np.asarray(bundle["class_edges"], dtype=np.float64)
        self.sfreq = float(sfreq)
        self.stream = None
        self.reset_state()

    def reset_state(self):
        """Called by the evaluator on a fresh copy at the start of every recording."""
        if self.stream is not None:
            self.stream.reset()
        self.prev_out = None

    def _smooth(self, pred, dt):
        out = np.empty_like(pred)
        for i, p in enumerate(pred):
            if self.prev_out is None or SMOOTH_A == 0:
                s = p
            else:
                s = SMOOTH_A * max(self.prev_out - dt, 0.0) + (1.0 - SMOOTH_A) * p
            out[i] = self.prev_out = s
        return out

    def predict(self, X):
        # X: (B, C, T) consecutive windows of the current recording, in time order.
        x = X.detach().float().cpu().numpy()
        if self.stream is None:
            self.stream = CausalFeatureStream(x.shape[-1] / self.sfreq, self.groups,
                                              core_index(range(x.shape[1])))
        # float32 round trip = exactly the training-time path (features cached as float32).
        f = window_features(x, self.sfreq).astype(np.float32).astype(np.float64)
        rows = np.stack([self.stream.update(fi) for fi in f]).astype(np.float32)
        if self.padded is not None:
            rows = apply_padded_edges(rows, *self.padded)
        elif self.bin_edges is not None:
            rows = apply_bin_edges(rows, self.bin_edges)
        if self.trees is not None:
            if self.kind == "dist":
                pred = decide(hgb_predict_proba(self.trees, rows), self.reps, self.omega, self.class_edges)
            else:
                pred = hgb_predict(self.trees, rows)
        elif self.kind == "dist":
            pred = decide(self.model.predict_proba(rows), self.reps, self.omega, self.class_edges)
        else:
            pred = np.asarray(self.model.predict(rows), dtype=np.float64)
        if CALIB_X is not None:
            pred = np.interp(pred, CALIB_X, CALIB_Y)
        pred = self._smooth(np.asarray(pred, dtype=np.float64), self.stream.step_s)
        pred = np.clip(np.nan_to_num(pred, nan=0.0), 0.0, 600.0)
        return torch.as_tensor(pred, dtype=torch.float32, device=X.device)


class Solver(CompetSolver):
    name = "HGBCausalFeatures"

    def load_model(self, meta):
        bundle = joblib.load(meta["submission_dir"] / "model.joblib")
        return HGBStreamModel(bundle.get("model"), meta["sfreq"], bundle.get("bin_edges"), bundle)
