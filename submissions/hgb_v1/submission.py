"""Track 03 submission: HistGradientBoostingRegressor (absolute error, W-bMAE weights) on causal
EEG features. Generated by scripts/build_hgb_submission.py -- do not edit by hand.

Per window: log band powers / ratios / artifact indicators per channel; per recording (state reset
at each recording): causal EMAs (30 s, 2 min, 5 min), difference to the recording's first-2-min
mean, elapsed time (= windows seen x window length). Never uses future windows or the recording end.
"""
import joblib
import numpy as np
import torch
from benchmark_utils.base_solver import CompetSolver
from scipy.signal import welch

# ---- verbatim copy of scripts/causal_features.py ----
BANDS = (("delta", 0.5, 4.0), ("theta", 4.0, 8.0), ("alpha", 8.0, 12.0),
         ("sigma", 12.0, 15.0), ("beta", 15.0, 30.0))
PER_CHANNEL = [b[0] for b in BANDS] + ["theta_alpha", "slow_fast", "var", "linelen", "maxabs"]
EMA_TAUS_S = (30.0, 120.0, 300.0)
BASELINE_S = 120.0
EPS = 1e-6


def window_features(X, sfreq):
    """X: (B, C, T) array in microvolts -> (B, C * len(PER_CHANNEL)) float64, channel-major."""
    X = np.nan_to_num(np.asarray(X, dtype=np.float64), nan=0.0, posinf=0.0, neginf=0.0)
    X = X - X.mean(axis=-1, keepdims=True)
    n_times = X.shape[-1]
    freqs, psd = welch(X, fs=sfreq, nperseg=min(int(2 * sfreq), n_times), axis=-1)
    df = freqs[1] - freqs[0]
    bp = {name: psd[..., (freqs >= lo) & (freqs < hi)].sum(axis=-1) * df for name, lo, hi in BANDS}
    feats = [np.log10(bp[name] + EPS) for name, _, _ in BANDS]
    feats.append(np.log10(bp["theta"] + EPS) - np.log10(bp["alpha"] + EPS))
    feats.append(np.log10(bp["delta"] + bp["theta"] + EPS) - np.log10(bp["alpha"] + bp["beta"] + EPS))
    feats.append(np.log10(X.var(axis=-1) + EPS))
    feats.append(np.log10(np.abs(np.diff(X, axis=-1)).mean(axis=-1) + EPS))
    feats.append(np.log10(np.abs(X).max(axis=-1) + EPS))
    out = np.stack(feats, axis=-1)  # (B, C, F)
    return out.reshape(out.shape[0], -1)


def feature_names(ch_names):
    base = [f"{ch}_{f}" for ch in ch_names for f in PER_CHANNEL]
    cur = base + [f"{n}_ema{int(t)}s" for t in EMA_TAUS_S for n in base]
    return cur + [f"{n}_rel" for n in cur] + ["elapsed_s"]


class CausalFeatureStream:
    """Stateful causal feature builder for one recording; ``reset()`` before each recording."""

    def __init__(self, step_s):
        self.step_s = float(step_s)
        self.alphas = [1.0 - np.exp(-self.step_s / tau) for tau in EMA_TAUS_S]
        self.reset()

    def reset(self):
        self.n_seen = 0
        self.emas = None
        self.base_sum = None
        self.base_n = 0

    def update(self, f):
        """f: (F,) window features of the newest window -> full causal feature vector."""
        self.n_seen += 1
        elapsed = self.n_seen * self.step_s
        if self.emas is None:
            self.emas = [f.copy() for _ in self.alphas]
            self.base_sum = np.zeros_like(f)
        else:
            for ema, a in zip(self.emas, self.alphas):
                ema += a * (f - ema)
        if elapsed <= BASELINE_S + 1e-9 or self.base_n == 0:
            self.base_sum += f
            self.base_n += 1
        base = self.base_sum / self.base_n
        cur = [f] + self.emas
        return np.concatenate(cur + [c - base for c in cur] + [np.array([elapsed])])

# ---- end of causal_features.py ----


class HGBStreamModel:
    def __init__(self, model, sfreq):
        self.model = model
        self.sfreq = float(sfreq)
        self.stream = None
        self.reset_state()

    def reset_state(self):
        """Called by the evaluator on a fresh copy at the start of every recording."""
        if self.stream is not None:
            self.stream.reset()

    def predict(self, X):
        # X: (B, C, T) consecutive windows of the current recording, in time order.
        x = X.detach().float().cpu().numpy()
        if self.stream is None:
            self.stream = CausalFeatureStream(step_s=x.shape[-1] / self.sfreq)
        # float32 round trip = exactly the training-time path (features cached as float32).
        f = window_features(x, self.sfreq).astype(np.float32).astype(np.float64)
        rows = np.stack([self.stream.update(fi) for fi in f]).astype(np.float32)
        pred = self.model.predict(rows)
        pred = np.clip(np.nan_to_num(pred, nan=0.0), 0.0, 600.0)
        return torch.as_tensor(pred, dtype=torch.float32, device=X.device)


class Solver(CompetSolver):
    name = "HGBCausalFeatures"

    def load_model(self, meta):
        bundle = joblib.load(meta["submission_dir"] / "model.joblib")
        return HGBStreamModel(bundle["model"], meta["sfreq"])
