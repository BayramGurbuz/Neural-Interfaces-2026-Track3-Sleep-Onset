        if self.kind == "mix":  # + causal GRU members (3 seeds), mixed on the grid with weight alpha
            c = bundle["gru_cfg"]
            self.gru_mu = np.asarray(bundle["gru_mu"], np.float32)
            self.gru_sd = np.asarray(bundle["gru_sd"], np.float32)
