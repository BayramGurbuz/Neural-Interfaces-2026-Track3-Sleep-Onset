BANDS = (("delta", 0.5, 4.0), ("theta", 4.0, 8.0), ("alpha", 8.0, 12.0),
         ("sigma", 12.0, 15.0), ("beta", 15.0, 30.0))
PER_CHANNEL = [b[0] for b in BANDS] + ["theta_alpha", "slow_fast", "var", "linelen", "maxabs"]
